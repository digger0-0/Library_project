/**
 * Create <app>/.env for a portable build on first launch.
 *
 * Why this exists:
 *   Next's output tracing copies the build machine's .env — including its real
 *   SESSION_SECRET — into .next/standalone, so a naive portable zip shipped a
 *   working secret. Anyone who unzipped a release could mint valid admin session
 *   cookies. The build scripts now delete that traced .env and ship
 *   .env.example instead; this script fills in a per-installation secret.
 *
 * Usage (from the app/ directory, using the bundled Node):
 *   node ensure-env.mjs [appDir]
 *
 * Safe to run on every start: it exits immediately when .env already exists, so
 * a user's edited configuration is never overwritten.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import path from "node:path";

const appDir = process.argv[2] ?? process.cwd();
const envPath = path.join(appDir, ".env");
const examplePath = path.join(appDir, ".env.example");

if (existsSync(envPath)) {
  // ASCII only: this runs in the user's console, and the Windows codepage would
  // render an em dash as mojibake.
  console.log(".env already exists - leaving it untouched.");
  process.exit(0);
}

if (!existsSync(examplePath)) {
  // Fail loudly rather than writing a partial .env: a missing RENEWAL_PERIOD
  // reaches sqliteDueDate() as NaN and throws "Invalid time value" on renew.
  console.error(`Cannot create .env: ${examplePath} not found.`);
  process.exit(1);
}

let body = readFileSync(examplePath, "utf8");
if (!body.endsWith("\n")) body += "\n";

// 32 bytes of CSPRNG output -> 64 hex chars. Generated per installation on
// purpose; shipping one value in the zip is exactly the bug this replaces.
const secret = randomBytes(32).toString("hex");

body += `\n# Generated by ensure-env.mjs on first launch. Keep this file private.\n`;
body += `SESSION_SECRET="${secret}"\n`;

// 0600 on POSIX; the mode argument is ignored on Windows, where the file
// inherits the folder's ACL.
writeFileSync(envPath, body, { mode: 0o600 });

console.log(`Created ${envPath} with a freshly generated SESSION_SECRET.`);
